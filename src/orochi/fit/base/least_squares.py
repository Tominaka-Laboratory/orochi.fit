class _FallbackParam:
    """Lightweight parameter container used when lmfit is not installed."""
    def __init__(self, name, value=0.0, min=-np.inf, max=np.inf, vary=True):
        self.name = name
        self.value = float(value)
        self.init_value = float(value)
        self.min = float(min) if min is not None else -np.inf
        self.max = float(max) if max is not None else np.inf
        self.vary = bool(vary)
        self.stderr = None

    def set(self, value=None, min=None, max=None, vary=None):
        if value is not None:
            self.value = float(value)
        if min is not None:
            self.min = float(min)
        if max is not None:
            self.max = float(max)
        if vary is not None:
            self.vary = bool(vary)


class _FallbackParameters(dict):
    """Lightweight Parameters dictionary used when lmfit is not installed."""
    def add(self, name, value=0.0, min=-np.inf, max=np.inf, vary=True):
        self[name] = _FallbackParam(name, value=value, min=min, max=max, vary=vary)


class _FallbackModelResult:
    """Lightweight fit result container used when lmfit is not installed."""
    def __init__(self, params, chisqr, rsquared, raw_result=None, best_fit=None, residual=None):
        self.params = params
        self.chisqr = chisqr
        self.rsquared = rsquared
        self.raw_result = raw_result
        self.best_fit = best_fit
        self.residual = residual



class LeastSquaresOptimizer(BaseOptimizer):
    r"""
    Performs least-squares optimization using Lmfit for Orochi modules.

    This class extends `BaseOptimizer` to provide a specific implementation
    for least-squares fitting of data generated by Orochi modules. It leverages
    the robust optimization capabilities of the Lmfit library to find the best-fit
    parameters that minimize the difference between simulated and observed data.

    It manages the creation of `lmfit.Model` instances from Orochi simulator
    modules, sets up `lmfit.Parameters` with appropriate bounds, executes
    the fitting process, and propagates the optimized parameters back to
    the original Orochi modules.

    Attributes
    ----------
    models : lmfit.model.CompositeModel or lmfit.model.Model or None
        The `lmfit` model (can be a composite of multiple models) constructed
        from the Orochi modules. It is `None` until `set_lmfit_models` is called.
    lmfit_params : lmfit.Parameters or None
        The `lmfit.Parameters` object containing all optimizable parameters
        for the fit. Created by `set_lmfit_models` from `self.models`. It is `None`
        until `set_lmfit_models` is called.
    obsx : numpy.ndarray or None
        A subset of the observed independent variable data (`self["obsx"]`)
        that falls within the specified fitting range [`fit_min`, `fit_max`].
        Populated during the `fit_least_squares` method. Inherited from `BaseOptimizer`.
    obsy : numpy.ndarray or None
        A subset of the observed dependent variable data (`self["obsy"]`)
        corresponding to `self.obsx`. Populated during the `fit_least_squares` method. Inherited from `BaseOptimizer`.
    res : lmfit.model.ModelResult or None
        The result object from the `lmfit` optimization process. This contains
        fit statistics, best-fit values, uncertainties, etc. Set by the `fit_least_squares` method.
    best_scores : dict
        A dictionary storing various goodness-of-fit scores for the best fit.
        Populated in `_summarize_scores`. Inherited from `BaseOptimizer`.
    fit_params : dict
        A dictionary to store detailed information about each parameter to be optimized,
        including its associated module, original address, initial value, min, and max bounds.
        This dictionary serves as the internal representation for building `lmfit.Parameters`.
        Inherited from `BaseOptimizer`.
    score_function : callable or None
        The function used to calculate the goodness-of-fit score. Defaults to a
        goodness-of-fit metric like Rw or user-provided. Inherited from `BaseOptimizer`.
    xscale : list
        A list of scaling factors for parameters, used by the `least_squares` method
        in `lmfit` to improve convergence. Populated in `set_lmfit_models`.

    Methods
    -------
    __call__()
        Executes the full least-squares optimization workflow.
    set_lmfit_models()
        Creates and configures the `lmfit.Parameters` object for the fitting process.
    _update_and_get_y(simulator)
        Creates a dynamic model function for `lmfit` to simulate data.
    _set_params_into_module(module, params_dict)
        Propagates parameter values from `lmfit` back into an Orochi module.
    fit_least_squares()
        Performs the actual `lmfit` optimization using the configured models and parameters.
    end_process_least_squares()
        Finalizes the optimization process by extracting, logging, and
        propagating the best-fit results.
    _summarize_params_and_update_modules(params)
        Extracts best-fit parameters from lmfit results and updates Orochi modules.
    _summarize_scores()
        Calculates and stores various goodness-of-fit scores.
    report()
        Generates and saves the optimization report. (Inherited and overridden from `BaseOptimizer` to use internal reporting data.)
    save_best_result()
        Saves the best observed and simulated data from the optimization. (Inherited from `BaseOptimizer`).
    simy (property)
        Calculates the best-fit simulated y-values based on the optimized modules. (Inherited from `BaseOptimizer`).
    set_callbacks()
        Sets up Optuna callbacks based on user parameters. (Inherited from `BaseOptimizer`).


    See Also
    --------
    orochi.base.core.OrochiBase : The base class for all modules within the Orochi framework.
    orochi.optimizer.base_optimizer.BaseOptimizer : The base class for optimizers in Orochi.
    lmfit.model.Model : The base class for models used in Lmfit for fitting.
    lmfit.Parameters : A specialized dictionary-like object for managing fit parameters.
    lmfit.model.ModelResult : The object containing the results of an Lmfit model fit.
    """

    def __init__(self):
        """
        Initialize the LeastSquaresOptimizer class.

        Sets up default parameter configurations specific to least-squares
        optimization from `.params.lmfit.default` and calls the `BaseOptimizer`
        initializer. It also sets the `name` attribute for this optimizer.
        """
        initial_par = getattr(self, "_par", getattr(self, "par", None))
        if initial_par is not None:
            par = copy.deepcopy(default.par)
            par.update(initial_par)
            self._par = par
        else:
            self._par = copy.deepcopy(default.par)

        key_info = copy.deepcopy(default.par_key_info)
        initial_key_info = getattr(self, "_par_key_info", getattr(self, "par_key_info", None))
        if initial_key_info is not None:
            key_info.update(initial_key_info)
        self._par_key_info = key_info
        super().__init__()

        self._name = "fit.least_squares"
        self._id = "0"
        
        self.models = None
        self.lmfit_params = None # Renamed from 'params' to 'lmfit_params' to avoid conflict with inherited 'params' property (if any, though not explicitly defined now).
        self.xscale = [] # Initialize xscale for least_squares method

    def __call__(self, force: bool = False):
        """
        Execute the complete optimization process using least squares.

        This method orchestrates the entire optimization workflow by sequentially
        calling several internal methods:
        1. Resets internal parameter and model storage to ensure a clean slate
           (`super().__call__(force=force)`).
        2. Sets up and configures the `lmfit.Model` instances for the simulators.
        3. Calls `set_lmfit_models` to create and initialize the `lmfit.Parameters`
           object with all optimizable parameters.
        4. Calls `fit_least_squares` to perform the actual least-squares optimization
           against the observed data using `lmfit`.
        5. Calls `end_process_least_squares` to finalize the optimization, extract best-fit
           results, and propagate the optimized parameters back to the original Orochi modules.
        6. Calls `report()` to generate and save the optimization summary.
        7. Calls `save_best_result()` to save the best observed and simulated data.
        """
        # Reset internal states for a fresh optimization run
        self._state = "OPTIMIZING"
        super().__call__(force=force)

        self.models = None
        self.lmfit_params = None
        self.set_lmfit_models()
        self.fit_least_squares()
        self.end_process_least_squares()
        self.report()
        self.save_best_result()
        self._state = "OPTIMIZED"

    def set_lmfit_models(self):
        """
        Create and configure the `lmfit.Parameters` object for the fitting process.

        This method iterates through the configured Orochi simulator modules,
        creates an `lmfit.Model` for each using `_update_and_get_y` as the
        model function, and combines them into `self.models`. It then
        generates an initial `lmfit.Parameters` object using `self.models.make_params()`.

        It populates `self.lmfit_params` and `self.xscale` (for `least_squares` method's
        parameter scaling) based on the optimizable parameters defined in `self.fit_params`.
        For each parameter, its value, min, max, and vary status are set or updated.
        """
        if lmfit is not None:
            for n, simulator in enumerate(self.simulators):    
                # Create an lmfit Model for the current simulator
                new_model = lmfit.models.Model(
                    self._update_and_get_y(simulator), prefix=self["prefix"]
                )

                # Combine models if multiple simulators are present
                if n == 0:
                    self.models = new_model
                else:
                    self.models = self.models + new_model

            self.lmfit_params = self.models.make_params()
        else:
            self.models = [self._update_and_get_y(sim) for sim in self.simulators]
            self.lmfit_params = _FallbackParameters()

        self.xscale = [] # Used for 'x_scale' in least_squares method
        
        for fit_name, value_dict in self.fit_params.items():
            if fit_name not in self.lmfit_params:
                # Add parameter if it's not already part of the model's default params
                vary_flag = value_dict.get("fit", value_dict.get("optimize", True))
                self.lmfit_params.add(
                    fit_name,
                    value=value_dict["value"],
                    min=value_dict["min"],
                    max=value_dict["max"],
                    vary=vary_flag,
                )
            else:
                # Update existing parameter's properties
                vary_flag = value_dict.get("fit", value_dict.get("optimize", True))
                self.lmfit_params[fit_name].set(
                    value=value_dict["value"],
                    min=value_dict["min"],
                    max=value_dict["max"],
                    vary=vary_flag,
                )
            # Populate xscale for least_squares method, which benefits from parameter scaling
            if self["method"] == "least_squares":
                # Ensure xscale is not zero to avoid division by zero errors in lmfit
                scale_val = value_dict["max"] - value_dict["min"]
                if scale_val == 0:
                    # If min and max are the same, use a small non-zero value or 1
                    scale_val = 1.0 if value_dict["value"] == 0 else abs(value_dict["value"] * 0.1)
                    if scale_val == 0: scale_val = 1.0 # Fallback if value is also zero
                self.xscale.append(scale_val)

    def _update_and_get_y(self, simulator):
        """
        Creates a dynamic model function for `lmfit` to simulate data from an
        Orochi simulator instance.

        This method generates and returns a callable function (`update`) that
        `lmfit` will repeatedly call during the optimization process.
        The `update` function acts as the core of the `lmfit.Model` and
        performs the following steps on each call:
        1. Takes the independent variable `x` (provided by `lmfit`) and
           the current `lmfit` parameters (`**params`).
        2. Iterates through the simulator's `nest_modules` and then the
           `simulator` itself, updating their internal parameter values
           from `**params` using `_set_params_into_module`. This effectively
           propagates the current trial parameter values from `lmfit` to the
           Orochi modules.
        3. Calls the `simulator` (which, in turn, may call its nested modules)
           to generate new simulated data based on the updated parameters.
        4. Retrieves the simulated x and y data from the simulator using
           `getattr(simulator, self["simx_attr"])` and
           `getattr(simulator, self["simy_attr"])`.
        5. Clears any "changed parameter" flags within the simulator and its
           nested modules, preparing them for the next iteration.
        6. Interpolates the simulated y-data (`simy`) onto the `x` grid
           (the observed x-data points provided by `lmfit`) using `scipy.interpolate.interp1d`.
           `bounds_error=False` and `fill_value=0.0` handle cases where `x`
           falls outside the simulated range.

        Parameters
        ----------
        simulator : OrochiBase
            An instance of an Orochi simulator module. It is expected to have
            `nest_modules` (a list of other Orochi modules), be callable to
            generate data, and have attributes named by `self["simx_attr"]`
            and `self["simy_attr"]` after being called.

        Returns
        -------
        function
            A model function suitable for direct use with `lmfit.models.Model`.
            This function has the signature `update(x, **params)`.
        """
        def update(x, **params):
            for module_attr in simulator["nest_modules"]:
                module = getattr(simulator, module_attr)
                self._set_params_into_module(module, params)
            self._set_params_into_module(simulator, params)
            
            # Call the simulator to generate new data with updated parameters
            simulator()
            
            # Retrieve simulated x and y data based on configured attribute names
            simx = getattr(simulator, self["simx_attr"], None)
            simy = getattr(simulator, self["simy_attr"], None)
            if simx is None or simy is None:
                raise RuntimeError(
                    f"Simulator '{getattr(simulator, 'study_name', 'pdfsim')}' failed to produce "
                    f"'{self['simx_attr']}' and '{self['simy_attr']}'. Simulator state: {getattr(simulator, '_state', 'UNKNOWN')}"
                )

            # Interpolate simulated y-data onto the observed x-grid
            y = intp.interp1d(
                simx, simy, bounds_error=False, fill_value=0.0
            )(x)

            # Clear changed parameter flags to prevent unnecessary re-calculations
            for module in simulator["nest_modules"]:
                module = getattr(simulator, module)
                module._clear_changed_parameters()
            simulator._clear_changed_parameters()
            
            return y

        return update

    def _set_params_into_module(self, module, params_dict):
        """
        Propagate parameter values from `lmfit` back into an Orochi module.

        This method is called by the `_update_and_get_y` function during each
        iteration of the `lmfit` optimization. It takes the current trial
        parameter values (`params_dict`) provided by `lmfit` and updates the
        corresponding parameters within the specified Orochi `module`.

        For each parameter in `params_dict`:
        1. It constructs the `fit_name` (the key used in `self.fit_params`).
           This involves potentially prepending `self.prefix` if the name from
           `lmfit` doesn't already include it.
        2. It uses `self.fit_params` to find the original Orochi string address
           corresponding to the `fit_name`.
        3. It then updates the parameter's "value" in the `module` using this
           Orochi address, allowing the module to use the latest parameter
           values for its calculations.

        Parameters
        ----------
        module : OrochiBase
            The Orochi module (e.g., Simulator, Phase) whose parameters need
            to be updated.
        params_dict : dict
            A dictionary where keys are `lmfit` parameter names (possibly without
            the prefix if `lmfit` has already stripped it) and values are their
            current numerical values during the optimization iteration.

        Returns
        -------
        OrochiBase
            The updated Orochi `module` instance.
        """
        prefix = self["prefix"]
        for name, value in params_dict.items():
            if name == "kws": # Skip lmfit's internal keyword arguments
                continue

            # Reconstruct the fit_name key for lookup in self.fit_params
            param_key_for_lookup = name
            if not param_key_for_lookup.startswith(prefix):
                param_key_for_lookup = prefix + param_key_for_lookup
            if not param_key_for_lookup.startswith(f"{prefix}{module._id}"):
                continue                 
            
            # If this fit_name corresponds to an Orochi parameter we manage, update it
            if param_key_for_lookup in self.fit_params:
                module_info = self.fit_params[param_key_for_lookup] # Get original Orochi address
                module = module_info["module"]
                module_address = module_info["address"]
                module[module_address] = value # Update the parameter's value in the module
        return module


    def fit_least_squares(self):
        """
        Perform the `lmfit` optimization using the configured models and parameters.

        This method executes the core fitting process:
        1. Filters the full observed data (`self["obsx"]`, `self["obsy"]`) to
           include only points within the specified `fit_min` and `fit_max` range,
           storing them in `self.obsx` and `self.obsy`.
        2. Checks if any data points remain after filtering; if not, logs a warning
           and sets `self.res` to `None`.
        3. Validates that `self.models` and `self.lmfit_params` have been successfully
           set up; if not, logs an error and returns.
        4. Prepares `fit_kws` (keyword arguments for the fitting algorithm) based
           on the chosen `method`. For "least_squares", it sets `ftol`, `xtol`, `gtol`,
           `x_scale` (derived from parameter ranges), and `diff_step`.
        5. Calls `self.models.fit()` with the prepared observed data, parameters,
           chosen method, and other configurations (`max_nfev`, `iter_cb`).
           The `kws` argument passes `self.simulators` which might be used by
           custom iteration callbacks.
        6. Stores the resulting `lmfit.model.ModelResult` object in `self.res`.
        """
        obsx_full = np.array(self["obsx"])
        obsy_full = np.array(self["obsy"])
        fit_min_val = self["fit_min"]
        fit_max_val = self["fit_max"]

        # Filter observed data to fit range
        valid_indices = (obsx_full >= fit_min_val) & (obsx_full <= fit_max_val)
        self.obsx = obsx_full[valid_indices]
        self.obsy = obsy_full[valid_indices]

        if len(self.obsx) == 0:
            self._logger.info("No data points found in the specified fitting range. Fit cannot be performed.")
            self.res = None
            return
        
        if self.models is None or self.lmfit_params is None:
            self._logger.error("Lmfit models or parameters were not set up correctly. Cannot perform fit.")
            return

        if lmfit is None:
            vary_keys = [k for k, p in self.lmfit_params.items() if p.vary]
            if not vary_keys:
                self._logger.warning("No varying parameters specified for fit.")
                self.res = None
                return

            x0 = np.array([self.lmfit_params[k].value for k in vary_keys], dtype=float)
            lb = np.array([self.lmfit_params[k].min for k in vary_keys], dtype=float)
            ub = np.array([self.lmfit_params[k].max for k in vary_keys], dtype=float)
            x0 = np.clip(x0, lb, ub)

            def _residual(vec):
                p_dict = {k: p.value for k, p in self.lmfit_params.items()}
                for k, val in zip(vary_keys, vec):
                    p_dict[k] = float(val)
                y_calc = np.zeros_like(self.obsx, dtype=float)
                for model_fn in self.models:
                    y_calc += model_fn(self.obsx, **p_dict)
                return y_calc - self.obsy

            xscale_arr = np.array(self.xscale) if len(self.xscale) == len(vary_keys) else 1.0
            rel_step = float(self["diff_step"]) if (self["diff_step"] is not None and 0 < float(self["diff_step"]) < 0.05) else 1e-4
            ls_res = scipy_least_squares(
                _residual,
                x0,
                bounds=(lb, ub),
                ftol=self["ftol"],
                xtol=self["xtol"],
                gtol=self["gtol"],
                x_scale=xscale_arr,
                diff_step=rel_step,
                loss="linear",
                max_nfev=self["max_nfev"],
            )

            for k, val in zip(vary_keys, ls_res.x):
                self.lmfit_params[k].value = float(val)

            chisqr = float(np.sum(ls_res.fun ** 2))
            ss_tot = float(np.sum((self.obsy - np.mean(self.obsy)) ** 2))
            rsquared = 1.0 - chisqr / ss_tot if ss_tot > 0 else 0.0

            dof = max(1, len(self.obsy) - len(vary_keys))
            s_sq = chisqr / dof
            try:
                cov = np.linalg.pinv(ls_res.jac.T @ ls_res.jac) * s_sq
                stderrs = np.sqrt(np.maximum(0.0, np.diag(cov)))
                for k, err in zip(vary_keys, stderrs):
                    self.lmfit_params[k].stderr = float(err)
            except Exception:
                pass

            calc_y = self.obsy + ls_res.fun
            self.res = _FallbackModelResult(
                self.lmfit_params,
                chisqr=chisqr,
                rsquared=rsquared,
                raw_result=ls_res,
                best_fit=calc_y,
                residual=ls_res.fun,
            )
            return

        # Prepare fit-specific keyword arguments based on the optimization method
        if self["method"] == "least_squares":
            rel_step = float(self["diff_step"]) if (self["diff_step"] is not None and 0 < float(self["diff_step"]) < 0.05) else 1e-4
            fit_kws = {
                "ftol": self["ftol"],
                "xtol": self["xtol"],
                "gtol": self["gtol"],
                "x_scale": np.array(self.xscale), # Use parameter ranges for scaling
                "diff_step": rel_step,
                "loss":"huber",
                "f_scale":0.1,
                # "tr_solver":"lsmr"
            }
        else:
            fit_kws = {} # No special kws for other methods by default

        # Perform the actual fit
        res = self.models.fit(
            data=self.obsy,
            x=self.obsx,
            params=self.lmfit_params,
            method=self["method"],
            kws={"modules": self.simulators}, # Pass simulators if iter_cb needs them
            verbose=True, # Show verbose output from lmfit
            max_nfev=self["max_nfev"],
            iter_cb=self["iter_cb"],
            fit_kws=fit_kws,
        )
        self.res = res


    def end_process_least_squares(self):
        """
        Finalize the optimization process by extracting, logging, and
        propagating the best-fit results for least squares.

        This method is called after the `fit_least_squares` method completes:
        1. Checks if `self.res` (the `lmfit.ModelResult` object) is available.
           If not, it logs a warning and sets relevant result attributes to `None`.
        2. Calls `_summarize_params_and_update_modules` to extract and propagate
           the best-fit parameters and their uncertainties to the Orochi modules.
        3. Calls `_summarize_scores` to calculate and store various goodness-of-fit scores.
        """
        if self.res is None:
            self.best_params = None
            self.best_scores = None
            return

        best_params = self.res.params
        self._summarize_params_and_update_modules(best_params)
        self._summarize_scores()


    def _summarize_params_and_update_modules(self, params):
        """
        Extracts best-fit parameters from `lmfit` results and updates Orochi modules.

        This method populates `self.best_params` with the best-fit parameter values
        and their standard errors (if available), mapping them back to their
        original Orochi module addresses. It also propagates these values and errors
        back into the respective Orochi modules.

        Parameters
        ----------
        params : lmfit.Parameters
            The `lmfit.Parameters` object containing the best-fit values
            and their associated uncertainties.
        """
        self.best_params = {}
        # Propagate best-fit parameters and errors back to the Orochi modules
        for fit_name, param_obj in params.items():
            if fit_name in self.fit_params: # Ensure this is a parameter we initialized
                module_info = self.fit_params[fit_name] # Get original Orochi name/address
                module = module_info["module"]
                module_address = module_info["address"]
                error_address = module_address.replace("value", "std") # Construct error address
                init_address = module_address.replace("value", "init")

                value = param_obj.value
                stderr = param_obj.stderr # Can be None if uncertainty wasn't calculated
                init_val = getattr(param_obj, "init_value", module_info.get("value", value))

                module[module_address] = value # Set the best-fit value
                if stderr is not None: # Only set error if it was calculated
                    module[error_address] = stderr

                self.best_params[module_address] = value
                self.best_params[error_address] = stderr
                self.best_params[init_address] = init_val


    def _summarize_scores(self):
        """
        Calculates and stores various goodness-of-fit scores for the optimization result.

        This method populates `self.best_scores` with relevant fit statistics
        (e.g., 'rsquared', 'chisqr') from the `lmfit.ModelResult` object (`self.res`).
        If a `score_function` is defined, it also calculates and stores the custom
        score (e.g., Rw) using the simulated and observed data.
        """
        self.best_scores = {}
        for key in ["rsquared", "chisqr"]:
            key = str(key)
            try:
                score = float(getattr(self.res, key))                
                self.best_scores[key] = score
            except AttributeError:
                self.best_scores[key] = None
        if self.score_function is not None:
            func = self.score_function(obsx=self.obsx, 
                                        obsy=self.obsy,
                                        simx_attr=self["simx_attr"],
                                        simy_attr=self["simy_attr"])
            key = str(self["score_type"])
            score = float(func(self.simulators))
            self.best_scores[key] = score

